const pdfParse = require("pdf-parse")
const {
    generateInterviewReport,
    generateResumePdf
} = require("../services/ai.service")

const interviewReportModel = require("../models/interviewReport.model")


/**
 * @description
 * Controller to generate interview report based on
 * resume, self description and job description.
 */
async function generateInterViewReportController(req, res) {

    try {

        const {
            title,
            selfDescription,
            jobDescription
        } = req.body


        // Validate required fields
        if (!title || !jobDescription) {
            return res.status(400).json({
                message: "Please provide title and job description."
            })
        }


        // User must provide either resume or self description
        if (!req.file && !selfDescription) {
            return res.status(400).json({
                message:
                    "Please provide either a resume or self description."
            })
        }


        // Validate PDF
        if (
            req.file &&
            req.file.mimetype !== "application/pdf"
        ) {
            return res.status(400).json({
                message:
                    "Only PDF resume files are supported."
            })
        }


        // Extract resume text
        let resumeText = ""


        if (req.file) {

            const resumeContent =
                await (
                    new pdfParse.PDFParse(
                        Uint8Array.from(req.file.buffer)
                    )
                ).getText()

            resumeText = resumeContent.text
        }


        // Generate report using Gemini
        const interviewReportByAi =
            await generateInterviewReport({

                resume: resumeText,

                selfDescription,

                jobDescription

            })


        console.log(
            "Interview Report generated by AI:",
            interviewReportByAi
        )


        // Save report in MongoDB
        const interviewReport =
            await interviewReportModel.create({

                user: req.user.id,

                title,

                resume: resumeText,

                selfDescription,

                jobDescription,

                ...interviewReportByAi

            })


        // Send response
        return res.status(201).json({

            message:
                "Interview report generated successfully.",

            interviewReport

        })


    } catch (error) {

        console.error(
            "Failed to generate interview report:",
            error
        )


        return res.status(
            error.statusCode || 500
        ).json({

            message:
                error.statusCode === 503
                    ? "Gemini AI is currently unavailable. Please try again later."
                    : "Unable to generate interview report."

        })

    }
}


/**
 * @description
 * Controller to get interview report by interviewId.
 */
async function getInterviewReportByIdController(req, res) {

    try {

        const { interviewId } = req.params


        const interviewReport =
            await interviewReportModel.findOne({

                _id: interviewId,

                user: req.user.id

            })


        if (!interviewReport) {

            return res.status(404).json({

                message:
                    "Interview report not found."

            })

        }


        return res.status(200).json({

            message:
                "Interview report fetched successfully.",

            interviewReport

        })

    } catch (error) {

        console.error(
            "Failed to fetch interview report:",
            error
        )

        return res.status(500).json({

            message:
                "Unable to fetch interview report."

        })
    }
}


/**
 * @description
 * Controller to get all interview reports
 * of the logged in user.
 */
async function getAllInterviewReportsController(req, res) {

    try {

        const interviewReports =
            await interviewReportModel

                .find({
                    user: req.user.id
                })

                .sort({
                    createdAt: -1
                })

                .select(
                    "-resume " +
                    "-selfDescription " +
                    "-jobDescription " +
                    "-__v " +
                    "-technicalQuestions " +
                    "-behavioralQuestions " +
                    "-skillGaps " +
                    "-preparationPlan"
                )


        return res.status(200).json({

            message:
                "Interview reports fetched successfully.",

            interviewReports

        })

    } catch (error) {

        console.error(
            "Failed to fetch interview reports:",
            error
        )

        return res.status(500).json({

            message:
                "Unable to fetch interview reports."

        })
    }
}


/**
 * @description
 * Controller to generate resume PDF based on
 * stored interview report.
 */
async function generateResumePdfController(req, res) {

    try {

        const { interviewReportId } = req.params


        // Make sure the report belongs to logged-in user
        const interviewReport =
            await interviewReportModel.findOne({

                _id: interviewReportId,

                user: req.user.id

            })


        if (!interviewReport) {

            return res.status(404).json({

                message:
                    "Interview report not found."

            })

        }


        const {
            resume,
            jobDescription,
            selfDescription
        } = interviewReport


        // Generate PDF
        const pdfBuffer =
            await generateResumePdf({

                resume,

                jobDescription,

                selfDescription

            })


        res.set({

            "Content-Type":
                "application/pdf",

            "Content-Disposition":
                `attachment; filename=resume_${interviewReportId}.pdf`

        })


        return res.send(pdfBuffer)


    } catch (error) {

        console.error(
            "Failed to generate resume PDF:",
            error
        )

        return res.status(500).json({

            message:
                "Unable to generate resume PDF."

        })
    }
}


module.exports = {

    generateInterViewReportController,

    getInterviewReportByIdController,

    getAllInterviewReportsController,

    generateResumePdfController

}
